SEASONAL_DAYS = (92.0, 93.0, 90.0, 90.0)


def seasonal_weight(t):
    """Return the number of days represented by time index ``t``."""

    hour = int(t)
    if not 0 <= hour < 96:
        raise IndexError(f"Time index must be in [0, 95], received {hour}.")
    return SEASONAL_DAYS[hour // 24]